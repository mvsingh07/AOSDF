#!/usr/bin/env python3
"""founder_inbox.py — decisions the founder owes, made visible (founder request 25Nov2026).

Agents used to stop silently when they needed the founder. Now:
  * an owner records the decision with `automode.py ask` (question, options, recommendation, what waits);
  * the relay also records every ESCALATE round, and any HOLD round naming the founder, by itself, so a
    forgotten `ask` still surfaces;
  * each new request raises one local macOS notification (no external service), and `automode.py watch`
    / `status` show open requests at the top;
  * the founder answers with `automode.py answer <id> --message ...`, which closes the request and sends a
    founder notice to the asker (and the SA), delivered by the relay with its normal guards.

Files: automation/var/owners/founder/<id>.json. Runtime state only; an answer is a founder instruction to
the agents, never itself a protected-operation authorization unless its text says so explicitly.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

import owner_wake as relay

INBOX = relay.owners.OWNERS / 'founder'
# documents/12_Manual_Actions/human-actions.md: the founder's learn/read/review/research/answer table (26Nov2026)
from layout import DOCUMENTS
HUMAN_ACTIONS = DOCUMENTS / '12_Manual_Actions' / 'human-actions.md'
TABLE_BEGIN, TABLE_END = '<!-- human-actions:begin (generated by automation/founder_inbox.py) -->', '<!-- human-actions:end -->'
LEARN_KINDS = ('learn', 'read', 'review', 'research', 'answer')
DECISION_ORIGINS = ('ask', 'auto-channel', 'budget', 'owner-error')
MAX_FIELD = 600
_FOUNDER_RE = re.compile(r'\bfounder\b', re.IGNORECASE)


def _clip(text: str | None, limit: int = MAX_FIELD) -> str:
    return ' '.join((text or '').split())[:limit]


def _load(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def requests(*, open_only: bool = True, learning: bool | None = False) -> list[dict]:
    """Inbox records. learning=False: decisions only (default); True: learn items only; None: everything."""
    out = []
    for path in sorted(INBOX.glob('*.json')):
        raw = _load(path)
        if not raw or (open_only and raw.get('status') != 'open'):
            continue
        if learning is not None and (raw.get('origin') == 'learn') != learning:
            continue
        out.append(raw)
    return sorted(out, key=lambda r: r.get('utc', ''))


def notify(title: str, message: str, runner=subprocess.run) -> bool:
    """One local desktop notification; silently skipped where osascript is unavailable."""
    if not shutil.which('osascript'):
        return False
    esc = lambda s: _clip(s, 220).replace('\\', '\\\\').replace('"', '\\"')  # noqa: E731
    try:
        runner(['osascript', '-e', f'display notification "{esc(message)}" with title "{esc(title)}" sound name "Glass"'],
               capture_output=True, timeout=10, check=False)
        return True
    except (OSError, subprocess.SubprocessError):
        return False


def _create(body: dict, key: str, runner=subprocess.run, title: str = '') -> tuple[dict, bool]:
    rid = hashlib.sha256(key.encode()).hexdigest()[:12]
    path = INBOX / f'{rid}.json'
    record = dict(body, id=rid, status='open', utc=relay.now().isoformat(), schema_version=1)
    try:
        relay._write_json(path, record, exclusive=True)
    except FileExistsError:
        return _load(path) or record, False
    record['notified'] = notify(title or f"Founder decision needed ({body['from']})", body['question'], runner)
    record['last_notified_utc'] = record['utc']
    relay._write_json(path, record)
    return record, True


def ask(role: str, question: str, *, thread: int | None = None, options: str = '', recommendation: str = '',
        blocked: str = '', wave_id: str = '', research: str = '', runner=subprocess.run) -> tuple[dict, bool]:
    if role not in relay.ROLES:
        raise ValueError(f'--from must be one of {relay.ROLES}')
    question = _clip(question)
    if len(question) < 10:
        raise ValueError('question must say what you need decided (10+ characters)')
    body = {'from': role, 'thread': thread, 'question': question, 'options': _clip(options),
            'recommendation': _clip(recommendation), 'blocked': _clip(blocked), 'wave_id': wave_id, 'origin': 'ask'}
    if research.strip():
        body['research'] = _clip(research)  # a decision that needs founder research also goes in human-actions.md
    out = _create(body, f'ask:{role}:{thread}:{question}', runner)
    render_human_actions()
    return out


def learn(role: str, kind: str, title: str, *, why: str = '', what: str = '', research: str = '',
          thread: int | None = None, task: str = '', link: str = '', wave_id: str = '',
          runner=subprocess.run) -> tuple[dict, bool]:
    """A NON-blocking founder item: something to learn, read, review, research or answer. Work continues."""
    if role not in relay.ROLES:
        raise ValueError(f'--from must be one of {relay.ROLES}')
    if kind not in LEARN_KINDS:
        raise ValueError(f'--kind must be one of {LEARN_KINDS}')
    title = _clip(title, 200)
    if len(title) < 10:
        raise ValueError('title must say what the founder should look at (10+ characters)')
    if len(_clip(why)) < 10:
        raise ValueError('--why must say why it matters to the founder (10+ characters)')
    if kind == 'research' and not research.strip():
        raise ValueError('--research must name what the founder should research')
    body = {'from': role, 'thread': thread, 'question': title, 'kind': kind, 'why': _clip(why), 'what': _clip(what),
            'research': _clip(research), 'task': _clip(task, 80), 'link': _clip(link, 300), 'wave_id': wave_id,
            'origin': 'learn', 'options': '', 'recommendation': '', 'blocked': ''}
    record, new = _create(body, f'learn:{role}:{kind}:{thread}:{title}', runner,
                          title=f'For you to {kind} ({role}) — work continues')
    render_human_actions()
    return record, new


def done(rid: str, note: str = '') -> dict:
    """Founder marks a learn/review/research item done (no notice is sent)."""
    record = _single(rid)
    record = close(record, 'done', note or 'done by founder')
    render_human_actions()
    return record


def _single(rid: str) -> dict:
    matches = list(INBOX.glob(f'{rid}*.json'))
    if len(matches) != 1:
        raise ValueError(f'no single request matches {rid!r}')
    record = _load(matches[0]) or {}
    if record.get('status') != 'open':
        raise ValueError(f"request {record.get('id')} is already {record.get('status')}")
    return record


def _cell(text) -> str:
    return ' '.join(str(text or '').split()).replace('|', '\\|') or '—'


def render_human_actions(path: Path | None = None) -> bool:
    """Regenerate the table in human-actions.md between its markers. Returns True when the file changed."""
    path = path or HUMAN_ACTIONS
    try:
        text = path.read_text(encoding='utf-8')
    except OSError:
        return False
    if TABLE_BEGIN not in text or TABLE_END not in text:
        return False
    rows = [r for r in requests(open_only=False, learning=None)
            if r.get('origin') == 'learn' or (r.get('origin') == 'ask' and r.get('research'))]
    rows.sort(key=lambda r: (r.get('status') != 'open', r.get('utc', '')), reverse=False)
    lines = ['| ID | Opened (UTC) | Type | From | Thread / task | What | Why it matters | Research on / where to look | Status |',
             '| --- | --- | --- | --- | --- | --- | --- | --- | --- |']
    for r in rows:
        kind = r.get('kind') or 'research-decision'
        where = '; '.join(x for x in (r.get('research'), r.get('link')) if x)
        what = r['question'] + (f" — {r['what']}" if r.get('what') else '')
        place = ' '.join(x for x in ((f"T{r['thread']}" if r.get('thread') else ''), r.get('task', '')) if x)
        status = r.get('status', 'open') + (f": {r['answer']}" if r.get('answer') else '')
        lines.append('| ' + ' | '.join(_cell(v) for v in (
            f"`{r['id']}`", r.get('utc', '')[:16].replace('T', ' '), kind, r.get('from'), place, what,
            r.get('why') or r.get('blocked'), where, status[:160])) + ' |')
    if len(rows) == 0:
        lines.append('| — | — | — | — | — | No items yet. | — | — | — |')
    head, rest = text.split(TABLE_BEGIN, 1)
    tail = rest.split(TABLE_END, 1)[1]
    new = head + TABLE_BEGIN + '\n' + '\n'.join(lines) + '\n' + TABLE_END + tail
    if new == text:
        return False
    tmp = path.with_suffix('.tmp')
    tmp.write_text(new, encoding='utf-8')
    tmp.replace(path)
    return True


def _minus_minutes(iso: str, minutes: int) -> str:
    import datetime as dt
    try:
        return (relay._date(iso) - dt.timedelta(minutes=minutes)).isoformat()
    except (TypeError, ValueError):
        return iso


def _round_text(text: str, start: int) -> str:
    import architect_bridge as bridge
    nxt = bridge._ROUND_RE.search(text, start + 1)
    return text[start:nxt.start() if nxt else len(text)]


def scan_channels(current: dict, runner=subprocess.run) -> list[dict]:
    """Auto-record ESCALATE rounds (and HOLD rounds naming the founder) of the current wave."""
    created = []
    for n in (1, 2, 3):
        latest = relay.latest_round(n)
        if not latest or latest.get('wave_id') != current['wave_id']:
            continue
        status = latest.get('status')
        if status not in ('ESCALATE', 'HOLD'):
            continue
        try:
            text = (relay.CHANNEL_DIR / f'thread{n}.md').read_text(encoding='utf-8')
        except OSError:
            continue
        import architect_bridge as bridge
        starts = [m.start() for m in bridge._ROUND_RE.finditer(text) if int(m.group(1)) == latest['round']]
        body_text = _round_text(text, starts[-1]) if starts else ''
        if status == 'HOLD' and not _FOUNDER_RE.search(body_text):
            continue
        opened = re.search(r'opened:(\S+)', body_text)
        since = opened.group(1) if opened else ''
        if since and any(r.get('origin') == 'ask' and r.get('thread') == n and r.get('wave_id') == current['wave_id']
                         and r.get('utc', '') >= _minus_minutes(since, 10) for r in requests(open_only=False)):
            continue  # the owner already asked the founder for this round
        prose = re.sub(r'<!--.*?-->', ' ', body_text, flags=re.S)
        prose = re.sub(r'(?m)^#+ .*$', ' ', prose)
        record, new = _create({'from': 'architect', 'thread': n, 'origin': 'auto-channel',
                               'question': f"T{n} Round {latest['round']} {status}: {_clip(prose, 480)}",
                               'options': '', 'recommendation': '', 'wave_id': current['wave_id'],
                               'blocked': f'thread {n}',
                               'round': latest['round'], 'round_status': status,
                               'source': f"coordinator-architect/thread{n}.md Round {latest['round']}"},
                              f"auto:{current['wave_id']}:{n}:{latest['round']}:{status}", runner)
        if new:
            created.append(record)
    return created


def _wake_usage(cfg: dict, current: dict) -> dict:
    """role -> (used, budget) of relay wakes in the current wave, for bound owners."""
    out = {}
    for role in cfg.get('owners', ()):
        rec = relay.binding_for(role)
        if not rec:
            continue
        used = sum(1 for s in relay._read_state(rec)['submissions'] if s.get('wave_id') == current['wave_id'])
        out[role] = (used, cfg['max_wakes_per_owner'])
    return out


def budget_warn_at(budget: int) -> int:
    """Remaining wakes at which the founder is warned: 2 for small budgets, ~1/8 for large (6 of 48)."""
    return max(2, budget // 8)


def budget_alerts(cfg: dict, current: dict, runner=subprocess.run) -> list[dict]:
    """Notify the founder once when an owner's wake budget is nearly used up, and once when it is exhausted."""
    created = []
    for role, (used, budget) in _wake_usage(cfg, current).items():
        left = budget - used
        if left > budget_warn_at(budget):
            continue
        level = 'exhausted' if left <= 0 else 'low'
        fix = ('it is at the 96 maximum, so only a new wave resets it' if budget >= 96 else
               f'raise max_wakes_per_owner in automation/config/owner_wake.json (now {budget}, max 96); '
               'the relay reads it on its next pass')
        head = (f'{role} wake budget EXHAUSTED ({used}/{budget}): the relay will not wake it again this wave'
                if level == 'exhausted' else f'{role} wake budget almost used: {used}/{budget}, {left} left')
        thread = int(role[-1]) if role.startswith('coordinator') else None
        record, new = _create({'from': role, 'thread': thread, 'origin': 'budget', 'question': f'{head}; {fix}.',
                               'options': '', 'recommendation': '', 'wave_id': current['wave_id'],
                               'blocked': f'relay wakes for {role}', 'budget_level': level, 'budget': budget},
                              f"budget:{current['wave_id']}:{role}:{level}:{budget}", runner)
        if new:
            created.append(record)
    return created


def last_turn_error(session_id: str | None) -> str:
    """The provider error that ended the owner's last Codex turn (usage limit, content policy...), if any."""
    if not session_id:
        return ''
    files = sorted(Path.home().glob(f'.codex*/sessions/*/*/*/*{session_id}.jsonl'), key=lambda p: p.stat().st_mtime)
    if not files:
        return ''
    try:
        with files[-1].open('rb') as fh:
            fh.seek(max(0, files[-1].stat().st_size - 400_000))
            lines = fh.read().decode('utf-8', 'replace').splitlines()
    except OSError:
        return ''
    for line in reversed(lines):
        if '"task_complete"' not in line:
            continue
        try:
            err = (json.loads(line).get('payload') or {}).get('error') or {}
        except ValueError:
            continue
        hint = {'usage_limit_exceeded': 'Codex usage limit reached: wait for the limit to reset (or raise the plan)',
                'cyber_policy': 'the provider content filter flagged the turn as cybersecurity risk: ask it to continue '
                                'with a rephrased, narrower instruction'}.get(err.get('codex_error_info'), '')
        return (hint or _clip(err.get('message'), 160)) if err else ''
    return ''


def owner_health(results: list[dict], current: dict, runner=subprocess.run) -> list[dict]:
    """Notify the founder once when an owner's session is in an error state (not busy), and close the alert
    as soon as that owner is reachable again. A stuck session must never look like a busy one."""
    created = []
    open_alerts = {r['from']: r for r in requests() if r.get('origin') == 'owner-error'}
    for o in results:
        role, state = o.get('role'), o.get('state')
        if state == 'owner-error':
            if role in open_alerts:
                continue
            thread = int(role[-1]) if role.startswith('coordinator') else None
            rec = relay.binding_for(role) or {}
            why = last_turn_error(rec.get('session_id'))
            record, new = _create({
                'from': role, 'thread': thread, 'origin': 'owner-error', 'wave_id': current['wave_id'],
                'question': (f"{role} session is stopped ({o.get('status')}), not busy: the relay cannot wake it. "
                             + (f'Cause: {why}. ' if why else 'Check its last turn in the Codex app. ')
                             + 'Then send it a message in the Codex app to continue (or rebind a fresh session); '
                             'the relay resumes waking it automatically once it is idle.'),
                'options': '', 'recommendation': '', 'blocked': f'all relay wakes for {role}'},
                f"owner-error:{current['wave_id']}:{role}:{relay.now().isoformat()}", runner,
                title=f'{role} is STOPPED, not busy')
            if new:
                created.append(record)
        elif role in open_alerts and state not in (None, 'error', 'skip-dispatch-busy'):
            close(open_alerts[role], 'superseded', f'{role} reachable again ({state})')
    return created


def close(record: dict, status: str, reason: str) -> dict:
    record.update(status=status, closed_reason=reason[:200], closed_utc=relay.now().isoformat())
    relay._write_json(INBOX / f"{record['id']}.json", record)
    return record


def reconcile(current: dict, cfg: dict | None = None) -> list[dict]:
    """Close what is no longer pending, so nothing resolved keeps notifying.

    * any open request from another wave -> superseded;
    * an auto-recorded round whose thread has moved past that round/status -> superseded;
    * a budget alert whose condition no longer holds (budget raised, or `low` became `exhausted`) -> superseded.
    `ask` requests in the current wave stay open until answered or dismissed by the founder.
    """
    closed = []
    latest = {n: relay.latest_round(n) or {} for n in (1, 2, 3)}
    usage = _wake_usage(cfg, current) if cfg else None
    for record in requests():
        if record.get('wave_id') and record['wave_id'] != current['wave_id']:
            closed.append(close(record, 'superseded', f"wave {record['wave_id']} ended"))
            continue
        if record.get('origin') == 'budget' and usage is not None:
            used, budget = usage.get(record['from'], (0, cfg['max_wakes_per_owner']))
            left = budget - used
            now_level = None if left > budget_warn_at(budget) else ('exhausted' if left <= 0 else 'low')
            if (now_level, budget) != (record.get('budget_level'), record.get('budget')):
                closed.append(close(record, 'superseded', f'budget now {used}/{budget}'))
            continue
        if record.get('origin') != 'auto-channel':
            continue
        if record.get('round') is None:  # records made before 25Nov 10:30Z: recover round/status from the text
            m = re.match(r'T\d Round (\d+) ([A-Z-]+):', record.get('question', ''))
            if m:
                record.update(round=int(m.group(1)), round_status=m.group(2))
        now_round = latest.get(record.get('thread'), {})
        if (now_round.get('round'), now_round.get('status')) != (record.get('round'), record.get('round_status')):
            closed.append(close(record, 'superseded',
                                f"thread moved on to Round {now_round.get('round')} {now_round.get('status')}"))
    return closed


def dismiss(rid: str, reason: str = 'dismissed by founder') -> dict:
    record = close(_single(rid), 'dismissed', reason)
    render_human_actions()
    return record


def remind_open(every_seconds: int = 3600, runner=subprocess.run) -> int:
    """Re-notify each still-open request at most once per `every_seconds`."""
    sent = 0
    for path in sorted(INBOX.glob('*.json')):
        record = _load(path)
        if not record or record.get('status') != 'open' or record.get('origin') in ('auto-channel', 'budget', 'learn', 'owner-error'):
            continue  # auto rounds/budget alerts close by themselves; learn items are non-blocking (table + watch)
        last = record.get('last_notified_utc') or record.get('utc')
        try:
            age = (relay.now() - relay._date(last)).total_seconds()
        except (TypeError, ValueError):
            age = every_seconds
        if age < every_seconds:
            continue
        notify(f"STILL WAITING on you ({record['from']})", record['question'], runner)
        record['last_notified_utc'] = relay.now().isoformat()
        relay._write_json(path, record)
        sent += 1
    return sent


def answer(rid: str, message: str, wave_id: str) -> dict:
    matches = [p for p in INBOX.glob(f'{rid}*.json')]
    if len(matches) != 1:
        raise ValueError(f'no single request matches {rid!r}')
    record = _load(matches[0]) or {}
    if record.get('status') != 'open':
        raise ValueError(f"request {record.get('id')} is already {record.get('status')}")
    roles = sorted({record['from'], 'architect'} | ({f"coordinator{record['thread']}"} if record.get('thread') else set()))
    roles = [r for r in roles if r in relay.ROLES]
    head = f"FOUNDER DECISION on {record['id']}"
    room = relay.MAX_NOTICE_CHARS - len(head) - 4
    text = f"{head}: {' '.join(message.split())}"
    if len(text) > relay.MAX_NOTICE_CHARS:
        raise ValueError(f'answer too long for one notice; keep it under {room} characters or point to a file')
    notice = relay.post_notice(roles, text, wave_id)
    record.update(status='answered', answer=' '.join(message.split()), answered_utc=relay.now().isoformat(),
                  notice=notice.stem, notified_roles=roles)
    relay._write_json(matches[0], record)
    render_human_actions()
    return record
