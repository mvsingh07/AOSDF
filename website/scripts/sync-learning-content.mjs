import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const hostingRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(hostingRoot, "..", "study_material", "modules");
const targetRoot = join(hostingRoot, "content", "learning");
const publishedIds = ["ml-foundations", "async-systems", "scale-design"];
const manifests = {};
const pages = {};

for (const id of publishedIds) {
  const source = join(sourceRoot, id);
  const target = join(targetRoot, id);
  const manifest = JSON.parse(await readFile(join(source, "manifest.json"), "utf8"));
  if (manifest.id !== id || !Array.isArray(manifest.lessons) || manifest.lessons.length === 0) {
    throw new Error(`Invalid or incomplete module manifest: ${id}`);
  }
  const files = [manifest.index, ...manifest.lessons.map(({ file }) => file)];
  const lessonIds = new Set(manifest.lessons.map(({ id }) => id));
  if (lessonIds.size !== manifest.lessons.length || files.length !== new Set(files).size) {
    throw new Error(`Duplicate lesson ID or filename: ${id}`);
  }
  pages[id] = {};
  await mkdir(target, { recursive: true });
  for (const file of files) {
    if (!/^[\w-]+\.md$/.test(file)) throw new Error(`Unsafe lesson filename: ${file}`);
    const markdown = await readFile(join(source, file), "utf8");
    const hasExercise = markdown.includes("## Try it") || markdown.includes("## Engineering exercise");
    const hasReview = markdown.includes("## Check your understanding") || markdown.includes("## Design review questions");
    if (!markdown.startsWith("# ") || (file !== manifest.index && (!hasExercise || !hasReview || !markdown.includes("## Diagram:")))) {
      throw new Error(`Incomplete lesson document: ${id}/${file}`);
    }
    pages[id][file] = markdown;
    await copyFile(join(source, file), join(target, file));
  }
  await copyFile(join(source, "manifest.json"), join(target, "manifest.json"));
  const assets = manifest.assets ?? [];
  if (!Array.isArray(assets) || assets.length !== new Set(assets).size) {
    throw new Error(`Invalid asset list: ${id}`);
  }
  if (assets.length) {
    const publicTarget = join(hostingRoot, "public", "learning", id);
    await mkdir(publicTarget, { recursive: true });
    for (const asset of assets) {
      if (!/^[\w-]+\.svg$/.test(asset)) throw new Error(`Unsafe asset filename: ${asset}`);
      const sourceAsset = join(source, "assets", asset);
      const svg = await readFile(sourceAsset, "utf8");
      if (!svg.includes("<svg") || svg.includes("<script") || svg.includes("http://www.w3.org/2000/svg") === false) {
        throw new Error(`Invalid SVG asset: ${id}/${asset}`);
      }
      await copyFile(sourceAsset, join(publicTarget, asset));
    }
  }
  manifests[id] = manifest;
  console.log(`Synced ${files.length} Markdown documents and ${assets.length} SVG assets for ${manifest.title}`);
}

await writeFile(join(hostingRoot, "lib", "learning-docs.generated.ts"),
  `// Generated by npm run sync:learning from AOSDF/study_material/modules.\nexport const moduleManifests = ${JSON.stringify(manifests, null, 2)} as const;\nexport const modulePages: Record<string, Record<string, string>> = ${JSON.stringify(pages, null, 2)};\n`);
